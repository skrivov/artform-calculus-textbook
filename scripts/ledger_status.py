#!/usr/bin/env python3
"""The status of the algebra of scores (the library ArtformScores).

Reads scores/manifest.toml and build/ledger-report.json (from
`lake env lean --run scripts/LedgerReport.lean`), and:
  --write    writes scores/STATUS.md;
  --check    fails when a manifest statement has no Lean statement with its label,
             when its proof does not prove exactly that statement or uses an axiom
             other than propext, Classical.choice and Quot.sound, when a Lean
             statement has no manifest entry, or when scores/STATUS.md is stale;
  --drift    lists the approved statements whose Lean text has changed since the
             review (report only: an approval stands until a review returns it);
  --approve KEY [KEY ...] [--date YYYY-MM-DD]
             records the judge's approval of the entries KEY.
It mirrors scripts/status.py, which does the same for the textbook.
"""
import argparse
import datetime
import hashlib
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "scores" / "manifest.toml"
STATUS_MD = ROOT / "scores" / "STATUS.md"
REVIEW_LOG = ROOT / "scores" / "review-log.md"
REPORT = ROOT / "build" / "ledger-report.json"
ALLOWED_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def text_hash(row):
    """The hash of what the reviewer reads: the statement and its definitions."""
    return sha("\n\n".join([row["text"], *row["surface"]]))


def load():
    manifest = tomllib.loads(MANIFEST.read_text(encoding="utf-8")).get("statement", [])
    report = json.loads(REPORT.read_text(encoding="utf-8"))
    return manifest, report


def evaluate(manifest, report):
    statements = {r["decl"]: r for r in report if r["kind"] == "statement"}
    proofs = {r["decl"]: r for r in report if r["kind"] == "proof"}
    results, problems = [], []
    for e in manifest:
        st = statements.get(e["lean_statement"])
        pr = proofs.get(e["lean_proof"])
        if st is None or st["label"] != e["label"]:
            problems.append(f"{e['key']}: no Lean statement {e['lean_statement']} with label {e['label']}")
            status = "planned"
        elif pr is None:
            status = "stated"
        elif pr["proves"] != e["lean_statement"] or pr["label"] != e["label"]:
            problems.append(f"{e['key']}: {e['lean_proof']} does not prove {e['lean_statement']}")
            status = "stated"
        elif set(pr["axioms"]) - ALLOWED_AXIOMS:
            problems.append(f"{e['key']}: {e['lean_proof']} uses {sorted(set(pr['axioms']) - ALLOWED_AXIOMS)}")
            status = "stated"
        else:
            status = "proved"
        drift = bool(e.get("reviewed")) and st is not None and text_hash(st) != e.get("review_text_sha256")
        results.append((e, status, drift))
    listed = {e["lean_statement"] for e in manifest}
    for decl in sorted(set(statements) - listed):
        problems.append(f"{decl}: a Lean statement with no manifest entry")
    return results, problems


def render(results):
    counts = {s: sum(1 for _, st, _ in results if st == s) for s in ("proved", "stated", "planned")}
    lines = ["# Status of the algebra of scores", "",
             "*Generated by `scripts/ledger_status.py` from `manifest.toml` and the ledger report; "
             "do not edit by hand.*", "",
             "| Status | Statements |", "|---|---|"]
    lines += [f"| {s} | {n} |" for s, n in counts.items()]
    lines += [f"| **total** | **{len(results)}** |", "", "## Statements", "",
              "| Key | Title | Status | Lean | Review |", "|---|---|---|---|---|"]
    for e, status, drift in results:
        review = (f"approved {e['reviewed']}" + (" (text changed since)" if drift else "")) \
            if e.get("reviewed") else "awaiting review"
        lines.append(f"| {e['key']} | {e['title']} | {status} | `{e['lean_statement']}` / "
                     f"`{e['lean_proof']}` | {review} |")
    return "\n".join(lines) + "\n"


def approve(keys, date, manifest, report):
    text = MANIFEST.read_text(encoding="utf-8")
    rows = {r["decl"]: r for r in report if r["kind"] == "statement"}
    entries = {e["key"]: e for e in manifest}
    log = []
    for key in keys:
        if key not in entries:
            sys.exit(f"{key}: no such manifest entry")
        row = rows.get(entries[key]["lean_statement"])
        if row is None:
            sys.exit(f"{key}: no Lean statement to approve")
        block = re.compile(r'(key = "' + re.escape(key) + r'"\n(?:(?!\[\[statement\]\]).*\n)*?)'
                           r'reviewed = ".*"\nreview_text_sha256 = ".*"\n')
        h = text_hash(row)
        text, n = block.subn(lambda m: m.group(1) + f'reviewed = "{date}"\nreview_text_sha256 = "{h}"\n', text)
        if n != 1:
            sys.exit(f"{key}: could not update its review fields")
        log.append(f"- {date}: `{key}` approved as `{row['decl']}` (text {h[:12]})")
    MANIFEST.write_text(text, encoding="utf-8")
    old = REVIEW_LOG.read_text(encoding="utf-8") if REVIEW_LOG.exists() else (
        "# Review log of the algebra of scores\n\nOne line per approval, written by "
        "`scripts/ledger_status.py --approve`.\n\n")
    REVIEW_LOG.write_text(old + "\n".join(log) + "\n", encoding="utf-8")
    print(f"approved: {', '.join(keys)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--drift", action="store_true")
    mode.add_argument("--approve", nargs="+", metavar="KEY")
    ap.add_argument("--date", default=datetime.date.today().isoformat())
    args = ap.parse_args()
    manifest, report = load()
    if args.approve:
        approve(args.approve, args.date, manifest, report)
        manifest, report = load()
    results, problems = evaluate(manifest, report)
    text = render(results)
    if args.drift:
        for e, _, drift in results:
            if drift:
                print(f"{e['key']}: the Lean text changed since the review of {e['reviewed']}")
        return
    if args.check:
        stale = not STATUS_MD.exists() or STATUS_MD.read_text(encoding="utf-8") != text
        for p in problems:
            print("problem:", p)
        if stale:
            print("problem: scores/STATUS.md is stale; run scripts/ledger_status.py --write")
        sys.exit(1 if problems or stale else 0)
    STATUS_MD.write_text(text, encoding="utf-8")
    for p in problems:
        print("problem:", p)
    print(f"wrote {STATUS_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
