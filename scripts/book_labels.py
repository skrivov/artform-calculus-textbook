#!/usr/bin/env python3
"""The book's numbers for the labels the guide cites.

The guide refers into the book ("Section 1.4", "Figure 1.9"). Those numbers
come from the book's .aux file. This script copies from it the \\newlabel
lines of every label the guide's LaTeX cites but does not define, so that the
guide builds without the book. It also writes the edition's name for the
guide's note. Run it locally whenever the repository follows a new edition:

  python3 scripts/book_labels.py BOOK_AUX EDITION_NUMBER "DATE"

for example
  python3 scripts/book_labels.py \\
      ../textbook/artform-calculus-and-applications.aux 54 "11 October 2026"

It writes tutorial/tex/generated/book-labels-<n>.tex, removes the
files of other editions, and writes tutorial/tex/generated/book-edition.tex.
It fails if a cited label is not in the .aux.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEX = ROOT / "tutorial" / "tex"
GENERATED = TEX / "generated"
REF = re.compile(r"\\(?:ref|cref|Cref|pageref|autoref|nameref)\{([^}]+)\}")
LABEL = re.compile(r"\\label\{([^}]+)\}")


def ordinal(n):
    if 10 <= n % 100 <= 13:
        return f"{n}th"
    return f"{n}" + {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    aux, number, date = Path(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    sources = sorted(TEX.glob("*.tex"))
    cited, defined = set(), set()
    for src in sources:
        text = re.sub(r"(?<!\\)%.*", "", src.read_text(encoding="utf-8"))
        for group in REF.findall(text):
            cited.update(x.strip() for x in group.split(","))
        defined.update(LABEL.findall(text))
    wanted = sorted(cited - defined)
    found = {}
    for line in aux.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"\\newlabel\{([^}]+)\}", line)
        if not m:
            continue
        base = m.group(1).removesuffix("@cref")
        if base in wanted:
            found.setdefault(base, []).append(line)
    missing = [w for w in wanted if w not in found]
    if missing:
        sys.exit("not in the book's .aux: " + ", ".join(missing))
    GENERATED.mkdir(parents=True, exist_ok=True)
    for old in GENERATED.glob("book-labels-*.tex"):
        old.unlink()
    out = GENERATED / f"book-labels-{number}.tex"
    lines = [f"% The book's numbers for the {len(wanted)} labels the guide cites, from the",
             f"% {ordinal(number)} edition's .aux ({date}). Generated by scripts/book_labels.py;",
             "% build.sh appends these lines to the guide's .aux. Do not edit."]
    for w in wanted:
        lines += found[w]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (GENERATED / "book-edition.tex").write_text(
        "% Generated by scripts/book_labels.py. Do not edit.\n"
        f"\\newcommand{{\\bookedition}}{{{ordinal(number)} edition ({date})}}\n",
        encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(wanted)} labels from {aux.name}")


if __name__ == "__main__":
    main()
