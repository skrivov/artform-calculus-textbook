#!/usr/bin/env python3
"""Certificate for the colour groups of Chapter 12 (Propositions 12.9, 12.13, 12.14 and
Theorem 12.16).

Writes the Lean file `textbook/ArtformTextbook/Ch12/ColourGroupsData.lean`, whose data
`textbook/ArtformTextbook/Ch12/ColourGroupsCheck.lean` checks with `decide +kernel`; the
proofs that use the checks are `Ch12/Groups*.lean`.

Every computation is exact, in Q(omega, phi) with phi^2 = phi + 1 and
omega^2 = -1 - omega, on the basis 1, phi, omega, phi omega (the Lean type
`Artform.Exact.ZOP`).

* The cube group: the 24 signed permutation matrices of determinant one.
* The icosahedral group: the sixty rotations of `icosahedron.py`, in the same order
  (`Artform.Icosahedron.gE`), packed as `gT`, with their permutations of the vertices
  (`permT`); `a5T` is their product table, read off the images of the base edge
  (vertices 0 and 4), and two rotations `a`, `b` generate the group, with a breadth-first
  tree `a5ParT` of words in them.
* Valentiner's group S(1080): the group generated by the 180 matrices omega^j g of
  C3 x A5 and the matrix F = [[1, 0, 0], [0, 0, omega], [0, -omega^2, 0]].  Its elements
  are written omega^j R_k c_i, with R_k a rotation and c_0, ..., c_5 representatives of
  the six right cosets of C3 x A5 (c_0 = 1, c_1 = F), each c_i the product c_p g of an
  earlier one and a generator.  The tables `cR` and `cc` give c_i R_k and c_d c_i in that
  form, which determines the product of any two elements; the element (j, k, i) is coded
  by j * 360 + k * 6 + i.  `invT` gives inverses; `labT` names the conjugacy class of each
  element by its row in the book's table (`fig:mm-s1080-classes`), `repT` a representative
  of each class and `conjT` an element conjugating each element to its representative.
  The script asserts that the group has 1080 elements, that it contains C3 x A5 with
  index 6, that the classes reproduce the book's sizes, orders and traces, and that the
  exponent is 60.

Tables of indices are packed into natural numbers, which the kernel reads with a shift and
a remainder; it computes slowly with integers, so only a few exact products of matrices
are checked (those with the generators), and the rest follows in Lean along the trees of
words that the tables `a5ParT` and `cosetParent` give.

Run with no arguments; the Lean text goes to standard output.
"""

import os
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import icosahedron  # noqa: E402  (the certificate of Proposition 12.8)


class K:
    """a + b phi + c omega + d phi omega, phi^2 = phi + 1, omega^2 = -1 - omega."""

    __slots__ = ("v",)

    def __init__(self, a=0, b=0, c=0, d=0):
        self.v = (Fraction(a), Fraction(b), Fraction(c), Fraction(d))

    def __add__(self, o):
        return K(*(x + y for x, y in zip(self.v, o.v)))

    def __sub__(self, o):
        return K(*(x - y for x, y in zip(self.v, o.v)))

    def __neg__(self):
        return K(*(-x for x in self.v))

    def __mul__(self, o):
        a, b, c, d = self.v
        e, f, g, h = o.v
        return K(a * e + b * f - c * g - d * h,
                 a * f + b * e + b * f - c * h - d * g - d * h,
                 a * g + b * h + c * e + d * f - c * g - d * h,
                 a * h + b * g + b * h + c * f + d * e + d * f - c * h - d * g - d * h)

    def scale(self, r):
        return K(*(x * r for x in self.v))

    def conj(self):
        a, b, c, d = self.v
        return K(a - c, b - d, -c, -d)

    def is_real(self):
        return self.v[2] == 0 and self.v[3] == 0

    def __eq__(self, o):
        return self.v == o.v

    def __hash__(self):
        return hash(self.v)


ZERO, ONE, PHI, OMEGA = K(0), K(1), K(0, 1), K(0, 0, 1)
OMEGA_POW = [ONE, OMEGA, OMEGA * OMEGA]


def mm(A, B):
    return tuple(tuple(sum((A[i][k] * B[k][j] for k in range(3)), ZERO) for j in range(3))
                 for i in range(3))


def smul(s, A):
    return tuple(tuple(s * x for x in row) for row in A)


def star(A):
    return tuple(tuple(A[j][i].conj() for j in range(3)) for i in range(3))


def transpose(A):
    return tuple(tuple(A[j][i] for j in range(3)) for i in range(3))


def trace(A):
    return A[0][0] + A[1][1] + A[2][2]


def det(A):
    return (A[0][0] * A[1][1] * A[2][2] - A[0][0] * A[1][2] * A[2][1]
            - A[0][1] * A[1][0] * A[2][2] + A[0][1] * A[1][2] * A[2][0]
            + A[0][2] * A[1][0] * A[2][1] - A[0][2] * A[1][1] * A[2][0])


I3 = tuple(tuple(ONE if i == j else ZERO for j in range(3)) for i in range(3))


def from_qphi(x):
    return K(x.a, x.b)


# ---------------------------------------------------------------- the cube group
def cube_group():
    from itertools import permutations, product
    out = []
    for perm in permutations(range(3)):
        for signs in product((1, -1), repeat=3):
            M = [[K(0)] * 3 for _ in range(3)]
            for i in range(3):
                M[i][perm[i]] = K(signs[i])
            M = tuple(tuple(r) for r in M)
            if det(M) == ONE:
                out.append(M)
    assert len(out) == 24 and len(set(out)) == 24
    return out


# ---------------------------------------------------------------- the icosahedral group
def ico_group():
    edges, mats, perm, inv = icosahedron.build()
    R = [tuple(tuple(from_qphi(x) for x in row) for row in g) for (g, _) in mats]
    G2 = [tuple(tuple(from_qphi(x) for x in row) for row in g2) for (_, g2) in mats]
    assert len(set(R)) == 60
    one = R.index(I3)
    edge_idx = [[0] * 12 for _ in range(12)]
    for k, (i, j) in enumerate(edges):
        edge_idx[i][j] = k
    return R, G2, perm, edge_idx, one


def a5_mul(perm, edge_idx, k, l):
    return edge_idx[perm[k][perm[l][0]]][perm[k][perm[l][4]]]


def order_in(mul, one, x):
    p, n = x, 1
    while p != one:
        p = mul(p, x)
        n += 1
    return n


def a5_generators(R, perm, edge_idx, one):
    mul = lambda k, l: a5_mul(perm, edge_idx, k, l)  # noqa: E731
    for k, x in enumerate(R):
        assert R[mul(k, k)] == mm(x, x)
    order = [order_in(mul, one, k) for k in range(60)]
    for a in range(60):
        if order[a] != 2:
            continue
        for b in range(60):
            if order[b] != 3:
                continue
            parent, depth = {one: None}, {one: 0}
            frontier = [one]
            while frontier:
                nxt = []
                for y in frontier:
                    for flag, g in ((True, a), (False, b)):
                        z = mul(g, y)
                        if z not in parent:
                            parent[z] = (flag, y)
                            depth[z] = depth[y] + 1
                            nxt.append(z)
                frontier = nxt
            if len(parent) == 60:
                return a, b, parent, depth, order
    raise AssertionError("no generating pair")


# ---------------------------------------------------------------- Valentiner's group
BOOK_TABLE = [  # fig:mm-s1080-classes, read column by column: (size, order, trace)
    (1, 1, ONE.scale(3)), (45, 2, -ONE), (1, 3, OMEGA.scale(3)), (1, 3, (OMEGA * OMEGA).scale(3)),
    (120, 3, ZERO), (120, 3, ZERO), (90, 4, ONE), (72, 5, PHI), (72, 5, ONE - PHI),
    (45, 6, -(OMEGA * OMEGA)), (45, 6, -OMEGA), (90, 12, OMEGA * OMEGA), (90, 12, OMEGA),
    (72, 15, (ONE - PHI) * OMEGA), (72, 15, PHI * OMEGA * OMEGA), (72, 15, PHI * OMEGA),
    (72, 15, (ONE - PHI) * OMEGA * OMEGA)]

F = ((ONE, ZERO, ZERO), (ZERO, ZERO, OMEGA), (ZERO, -(OMEGA * OMEGA), ZERO))


def lcm(a, b):
    from math import gcd
    return a * b // gcd(a, b)


def valentiner(R, G2, perm, edge_idx, one, a, b):
    Rkey = {x: k for k, x in enumerate(R)}

    def in_h(M):
        """(j, k) with M = omega^j R_k, or None."""
        for j in range(3):
            N = smul(OMEGA_POW[(3 - j) % 3], M)
            if N in Rkey:
                return j, Rkey[N]
        return None

    # coset representatives by breadth-first search over the right cosets H c
    gens = [F, R[a], R[b]]
    reps, rep_parent = [I3], [None]
    frontier = [0]
    while frontier:
        nxt = []
        for p in frontier:
            for gi, g in enumerate(gens):
                x = mm(reps[p], g)
                if all(in_h(mm(x, star(c))) is None for c in reps):
                    reps.append(x)
                    rep_parent.append((p, gi))
                    nxt.append(len(reps) - 1)
        frontier = nxt
    assert len(reps) == 6 and reps[1] == F

    def decompose(M):
        for i, c in enumerate(reps):
            h = in_h(mm(M, star(c)))
            if h is not None:
                return (h[0], h[1], i)
        raise AssertionError("not in the group")

    cR = [[decompose(mm(reps[i], R[k])) for k in range(60)] for i in range(6)]
    cc = [[decompose(mm(reps[d], reps[i])) for i in range(6)] for d in range(6)]
    amul = lambda k, l: a5_mul(perm, edge_idx, k, l)  # noqa: E731

    def mul(x, y):
        j, k, i = x
        j2, k2, i2 = y
        a1, b1, d1 = cR[i][k2]
        e1, f1, g1 = cc[d1][i2]
        return ((j + j2 + a1 + e1) % 3, amul(amul(k, b1), f1), g1)

    def mat(x):
        j, k, i = x
        return smul(OMEGA_POW[j], mm(R[k], reps[i]))

    elems = [(j, k, i) for j in range(3) for k in range(60) for i in range(6)]
    mats = {x: mat(x) for x in elems}
    assert len(set(mats.values())) == 1080
    for M in mats.values():
        for row in M:
            for x in row:
                for c in x.v:
                    assert (2 * c).denominator == 1
    # the product, against the matrices, on a sample of pairs
    import random
    rng = random.Random(1080)
    for _ in range(3000):
        x, y = rng.choice(elems), rng.choice(elems)
        assert mats[mul(x, y)] == mm(mats[x], mats[y])
    e = (0, one, 0)
    inv = {}
    for x in elems:
        y = decompose(star(mats[x]))
        assert mul(x, y) == e
        inv[x] = y
    # the generators and the coset tree
    for i in range(1, 6):
        p, gi = rep_parent[i]
        assert reps[i] == mm(reps[p], gens[gi])
    # conjugacy classes, by conjugation with a, b and F (the centre is central)
    tgen = [(0, a, 0), (0, b, 0), (0, one, 1)]

    def conj(t, x):
        return mul(mul(t, x), inv[t])

    label, classes = {}, []
    for x in elems:
        if x in label:
            continue
        cls = [x]
        label[x] = len(classes)
        k = 0
        while k < len(cls):
            for t in tgen:
                y = conj(t, cls[k])
                if y not in label:
                    label[y] = len(classes)
                    cls.append(y)
            k += 1
        classes.append(cls)
    assert len(classes) == 17
    # check that the labels are closed under conjugation by the generators
    for x in elems:
        for t in tgen:
            assert label[conj(t, x)] == label[x]
    order = {x: order_in(mul, e, x) for x in elems}
    tr = {x: trace(mats[x]) for x in elems}
    # match the classes with the rows of the book's table
    row_of = {}
    used = set()
    h_elems = {(j, k, 0) for j in range(3) for k in range(60)}
    # the class of order-3, trace-0 elements that meets C3 x A5 is row 4, the other row 5
    for ci, cls in enumerate(classes):
        x = cls[0]
        key = (len(cls), order[x], tr[x])
        assert all(order[y] == order[x] and tr[y] == tr[x] for y in cls)
        cands = [r for r, row in enumerate(BOOK_TABLE) if row == key and r not in used]
        assert cands, key
        if key == (120, 3, ZERO):
            r = 4 if any(y in h_elems for y in cls) else 5
        else:
            r = cands[0]
        assert r not in used
        used.add(r)
        row_of[ci] = r
    assert len(used) == 17
    lab = {x: row_of[label[x]] for x in elems}
    rep = [None] * 17
    for ci, cls in enumerate(classes):
        rep[row_of[ci]] = min(cls)
    # a conjugator for each element: g x g^{-1} = rep
    conjugator = {}
    for r in range(17):
        conjugator[rep[r]] = e
        queue = [rep[r]]
        k = 0
        while k < len(queue):
            z = queue[k]
            for t in tgen:
                y = conj(t, z)               # y = t z t^{-1}, so z = t^{-1} y t
                if y not in conjugator:
                    conjugator[y] = mul(conjugator[z], inv[t])
                    queue.append(y)
            k += 1
    assert len(conjugator) == 1080
    for x in elems:
        assert mul(conjugator[x], x) == mul(rep[lab[x]], conjugator[x])
    # the exponent
    ex = 1
    for x in elems:
        ex = lcm(ex, order[x])
    assert ex == 60
    # the subgroup C3 x A5 has index 6 and contains the centre
    assert len(h_elems) == 180
    return dict(reps=reps, rep_parent=rep_parent, cR=cR, cc=cc, inv=inv, lab=lab, rep=rep,
                conjugator=conjugator, elems=elems, mats=mats, order=order, tr=tr)


# ---------------------------------------------------------------- Lean output
#
# Index tables are packed into natural numbers, `w` bits an entry, entry `i` at bit `w * i`,
# so that the kernel reads an entry with one shift and one remainder on numerals.  A number
# is written as its base-2^320 digits, least significant first, one a line.

CHUNK = 320


def lean_int(x):
    assert x.denominator == 1
    n = int(x)
    return f"({n})" if n < 0 else str(n)


def lean_zop(x):
    return "z " + " ".join(lean_int(c) for c in x.v)


def lean_m3z_int(A):
    """An integer matrix, as `mi a b c d e f g h i`."""
    for row in A:
        for x in row:
            assert x.v[1] == 0 and x.v[2] == 0 and x.v[3] == 0
    return "mi " + " ".join(lean_int(x.v[0]) for row in A for x in row)


def lean_m3z_lines(A, factor, indent):
    """A matrix of `ℤ[ω, φ]`, three entries a line."""
    rows = [", ".join(lean_zop(x.scale(factor)) for x in row) for row in A]
    return [indent + "⟨" + rows[0] + ",", indent + " " + rows[1] + ",",
            indent + " " + rows[2] + "⟩"]


def chunks(items, width, indent):
    lines, cur = [], ""
    for it in items:
        piece = it if not cur else ", " + it
        if cur and len(indent + cur + piece) + 1 > width:
            lines.append(indent + cur + ",")
            cur = it
        else:
            cur += piece
    lines.append(indent + cur)
    return lines


def vec(items, indent="  "):
    """`![a, b, ...]` over several lines."""
    body = chunks(items, 99, indent)
    body[0] = indent + "![" + body[0][len(indent):]
    body[-1] += "]"
    return body


def pack(entries, w):
    N = 0
    for i, e in enumerate(entries):
        assert 0 <= e < (1 << w), (e, w)
        N |= e << (w * i)
    return N


def lean_packed(name, doc, entries, w):
    N = pack(entries, w)
    digits = []
    while N:
        digits.append(N & ((1 << CHUNK) - 1))
        N >>= CHUNK
    if not digits:
        digits = [0]
    out = [doc, f"def {name} : ℕ := ofChunks ["]
    for n, d in enumerate(digits):
        out.append("  0x%x%s" % (d, "," if n < len(digits) - 1 else "]"))
    out.append("")
    return out


def code(x):
    j, k, i = x
    return j * 360 + k * 6 + i


HEADER = """import ArtformTextbook.Exact.ZOmegaPhi

/-!
# Certificate data for the colour groups of Chapter 12

Written by `scripts/certificates/colour_groups.py`; every claim about these data is checked by
`decide +kernel` in `Ch12/ColourGroupsCheck.lean`. The rotations of the icosahedron are those
of `Artform.Icosahedron.gE` (`Ch12/Icosahedron.lean`), in the same order.

Tables of indices are packed into natural numbers: `entry w N i` is the `i`-th entry of `w`
bits of `N`, read by the kernel with one shift and one remainder. An element of Valentiner's
group is coded by `j * 360 + k * 6 + i`, for `j < 3`, `k < 60` and `i < 6`; it stands for
`ω^j R_k c_i`, `R_k` the `k`-th rotation of the icosahedron and `c_i` the `i`-th coset
representative.
-/

namespace Artform.ColourGroups

open Exact

/-- The number `a + b φ + c ω + d φ ω` of `ℤ[ω, φ]`. -/
def z (a b c d : ℤ) : ZOP := ⟨a, b, c, d⟩

/-- The integer matrix with rows `(a, b, c)`, `(d, e, f)` and `(g, h, i)`. -/
def mi (a b c d e f g h i : ℤ) : M3Z :=
  ⟨z a 0 0 0, z b 0 0 0, z c 0 0 0, z d 0 0 0, z e 0 0 0, z f 0 0 0, z g 0 0 0, z h 0 0 0,
   z i 0 0 0⟩

/-- The natural number with the base-`2^320` digits `ds`, least significant first. -/
def ofChunks : List ℕ → ℕ
  | [] => 0
  | d :: ds => d + ofChunks ds * 2 ^ 320

/-- The `i`-th entry of `w` bits of `N`. -/
def entry (w N i : ℕ) : ℕ := (N >>> (w * i)) % 2 ^ w
"""


def main():
    out = [HEADER]
    cube = cube_group()
    out.append("/-- The twenty-four signed permutation matrices of determinant one. -/")
    out.append("def cubeE : Fin 24 → M3Z :=")
    out.extend(vec([lean_m3z_int(M) for M in cube]))
    out.append("")
    R, G2, perm, edge_idx, one = ico_group()
    assert one == 1
    a, b, parent, depth, order5 = a5_generators(R, perm, edge_idx, one)
    out.extend(lean_packed(
        "permT", "/-- `perm k i` of `Ch12/Icosahedron.lean`, at entry `12 k + i` of 4 bits. -/",
        [perm[k][i] for k in range(60) for i in range(12)], 4))
    out.extend(lean_packed(
        "a5T", "/-- The product of the rotations `k` and `l`, at entry `60 k + l` of 6 bits. -/",
        [a5_mul(perm, edge_idx, k, l) for k in range(60) for l in range(60)], 6))
    digits = []
    for g2 in G2:
        for row in g2:
            for x in row:
                for c in (x.v[0], x.v[1]):
                    assert x.v[2] == 0 and x.v[3] == 0 and c.denominator == 1
                    assert -4 <= c < 4
                    digits.append(int(c) + 4)
    out.extend(lean_packed(
        "gT", "/-- The doubled rotations `gE k`, entry by entry, each `a + b φ` as the digits\n"
        "`a + 4` and `b + 4`: entry `18 k + 6 r + 2 c` holds `a + 4` for row `r` and column "
        "`c`. -/",
        digits, 3))
    out.append(f"/-- A rotation of order two; with `a5GenB` it generates the sixty. -/")
    out.append(f"def a5GenA : ℕ := {a}")
    out.append("")
    out.append(f"/-- A rotation of order three; with `a5GenA` it generates the sixty. -/")
    out.append(f"def a5GenB : ℕ := {b}")
    out.append("")
    par = []
    for k in range(60):
        if parent[k] is None:
            par.append(1)
        else:
            flag, y = parent[k]
            par.append((64 if flag else 0) + y)
    out.extend(lean_packed(
        "a5ParT", "/-- The tree of words in `a5GenA` and `a5GenB`: rotation `k`, other than the\n"
        "identity `1`, is `a5GenA` times `p` when entry `k` (7 bits) is `64 + p`, and `a5GenB`\n"
        "times `p` when it is `p < 64`. -/", par, 7))
    out.extend(lean_packed("a5DepT", "/-- The depth of each rotation in that tree (4 bits). -/",
                           [depth[k] for k in range(60)], 4))
    V = valentiner(R, G2, perm, edge_idx, one, a, b)
    out.append("/-- The six coset representatives `c_i`, doubled: `c_i = (cosetE i).toMat / 2`;")
    out.append("`c_0 = 1` and `c_1 = F`. -/")
    out.append("def cosetE : Fin 6 → M3Z :=")
    out.append("  ![")
    for n, c in enumerate(V["reps"]):
        lines = lean_m3z_lines(c, 2, "    ")
        if n < 5:
            lines[-1] += ","
        out.extend(lines)
    out.append("  ]")
    out.append("")
    out.append("/-- `c_i = c_p g` for `(p, g) = cosetParent i`, `i ≥ 1`, with `g` the generator")
    out.append("`F`, `a5GenA` or `a5GenB` for `g = 0, 1, 2`. -/")
    out.append("def cosetParent : Fin 6 → Fin 6 × Fin 3 :=")
    out.extend(vec(["(0, 0)"] + [f"({p}, {g})" for (p, g) in V["rep_parent"][1:]]))
    out.append("")
    elems = V["elems"]
    out.extend(lean_packed(
        "cRT", "/-- `c_i R_k`, coded, at entry `60 i + k` (11 bits). -/",
        [code(V["cR"][i][k]) for i in range(6) for k in range(60)], 11))
    out.extend(lean_packed(
        "ccT", "/-- `c_d c_i`, coded, at entry `6 d + i` (11 bits). -/",
        [code(V["cc"][d][i]) for d in range(6) for i in range(6)], 11))
    by_code = sorted(elems, key=code)
    assert [code(x) for x in by_code] == list(range(1080))
    out.extend(lean_packed("invT", "/-- The inverse of each element (11 bits). -/",
                           [code(V["inv"][x]) for x in by_code], 11))
    out.extend(lean_packed(
        "labT",
        "/-- The row of the book's class table that holds each element's class (5 bits). -/",
        [V["lab"][x] for x in by_code], 5))
    out.extend(lean_packed(
        "conjT", "/-- An element `g` with `g x g⁻¹` the representative of the class of `x`. -/",
        [code(V["conjugator"][x]) for x in by_code], 11))
    out.extend(lean_packed("repT", "/-- A representative of the class in each row (11 bits). -/",
                           [code(x) for x in V["rep"]], 11))
    out.append("/-- The trace of the triplet on each row of the table, exactly. -/")
    out.append("def traceZ : Fin 17 → ZOP :=")
    out.extend(vec(["(" + lean_zop(row[2]) + ")" for row in BOOK_TABLE]))
    out.append("")
    out.append("end Artform.ColourGroups")
    print("\n".join(out))


if __name__ == "__main__":
    main()
