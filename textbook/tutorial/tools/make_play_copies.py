#!/usr/bin/env python3
"""Write unguarded copies of the guide's two checked Lean files into play/.

In the checked files every answer is pinned by a pair
  /-- info: 5 -/        (or /-- error: ... -/)
  #guard_msgs in
which shows nothing in an editor while the answer is right. The play copies
turn each pair into a plain comment, so VS Code shows every answer in the
Infoview and every refusal as a red error. The checked files are untouched;
build.sh and extract_listings.py never read play/.
Run:  python3 tools/make_play_copies.py
"""
from pathlib import Path

TUTORIAL = Path(__file__).resolve().parent.parent
SOURCES = [TUTORIAL / "LeanBasics.lean",
           TUTORIAL / "ArtformChapter1.lean"]
OUT = TUTORIAL / "play"

HEADER = """-- Play copy of ../{name}, generated by tools/make_play_copies.py.
-- The #guard_msgs checks are removed: put the cursor on a line to see
-- Lean's answer in the Infoview. Lines marked "refused on purpose" are
-- meant to be red. Edit freely; regenerating overwrites this file.

"""


def unguard(lines):
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("/--"):
            j = i
            while not lines[j].rstrip().endswith("-/"):
                j += 1
            body = "\n".join(lines[i:j + 1])[3:-2].strip()
            if (j + 1 < len(lines) and lines[j + 1].strip() == "#guard_msgs in"
                    and body.split(":", 1)[0] in ("info", "error", "warning")):
                kind, text = body.split(":", 1)
                text = text.strip().splitlines()
                if kind == "info":
                    out.append("-- Lean answers: " + text[0])
                else:
                    out.append("-- Lean refuses this on purpose: " + text[0])
                out.extend("--   " + t for t in text[1:])
                i = j + 2
                continue
        out.append(line)
        i += 1
    return out


def main():
    OUT.mkdir(exist_ok=True)
    for src in SOURCES:
        lines = src.read_text(encoding="utf-8").splitlines()
        play = HEADER.format(name=src.name) + "\n".join(unguard(lines)) + "\n"
        (OUT / src.name).write_text(play, encoding="utf-8")
        print(f"wrote play/{src.name}")


if __name__ == "__main__":
    main()
